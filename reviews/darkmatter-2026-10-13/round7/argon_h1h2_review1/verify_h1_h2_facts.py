#!/usr/bin/env python3
"""Independent verification script for Argon Round 7 H1/H2 review.

Separates:
1. Manifest and SHA-256 verification of h1_final, h2_initial, and h2_v2 snapshots.
2. Direct table-lookup and cross-table consistency checks on H1 (h1_final) and H2 (h2_initial / h2_v2),
   including verification that h2_v2/H1_COMPLETENESS.md (generated by root_checks/generate_h1_summary.py)
   matches the authoritative h1_final TSV/JSON tables.
3. Targeted arithmetic and statistical recomputations from the local TSV tables (H2 attrition Fisher tests,
   Mantel-Haenszel point estimates, OLS/HC3 and Logit regressions on the 353 Tier 1 families, and
   cross-family dependence/disjoint-species counts).
"""
import csv
import hashlib
import json
from collections import defaultdict
from pathlib import Path
import numpy as np
import pandas as pd
from scipy import stats
import statsmodels.api as sm

ROOT = Path(__file__).resolve().parents[4]
H1_DIR = ROOT / "reviews/darkmatter-2026-10-13/round6/snapshots/h1_final"
H2_INIT_DIR = ROOT / "reviews/darkmatter-2026-10-13/round7/snapshots/h2_initial"
H2_V2_DIR = ROOT / "reviews/darkmatter-2026-10-13/round7/snapshots/h2_v2"
OUT_JSON = Path(__file__).resolve().parent / "verify_h1_h2_facts.json"


def verify_snapshot_manifest(snap_dir: Path) -> dict:
    manifest = json.loads((snap_dir / "SNAPSHOT_MANIFEST.json").read_text())
    files = manifest.get("files", [])
    matched = 0
    mismatches = []
    for entry in files:
        rel = entry["path"]
        expected = entry["sha256"]
        fp = snap_dir / rel
        actual = hashlib.sha256(fp.read_bytes()).hexdigest()
        if actual == expected:
            matched += 1
        else:
            mismatches.append({"path": rel, "expected": expected, "actual": actual})
    return {"total": len(files), "matched": matched, "mismatches": mismatches}


def main():
    report = {
        "snapshots_sha256": {
            "h1_final": verify_snapshot_manifest(H1_DIR),
            "h2_initial": verify_snapshot_manifest(H2_INIT_DIR),
            "h2_v2": verify_snapshot_manifest(H2_V2_DIR),
        }
    }

    # Check H2 outputs_sha256.txt
    out_sha_lines = (H2_V2_DIR / "results/outputs_sha256.txt").read_text().strip().splitlines()
    out_matched = 0
    for line in out_sha_lines:
        digest, rel_path = line.strip().split(None, 1)
        fp = H2_V2_DIR / "results" / Path(rel_path).name
        assert hashlib.sha256(fp.read_bytes()).hexdigest() == digest
        out_matched += 1
    report["h2_outputs_sha256_verified"] = out_matched

    # 1. Verify H1 authoritative tables and h2_v2/H1_COMPLETENESS.md repair
    h1_mod = pd.read_csv(H1_DIR / "results/v3_pgls_model_summary.tsv", sep="\t")
    h1_sens = pd.read_csv(H1_DIR / "results/v3_pgls_sensitivity.tsv", sep="\t")
    h1_prof = pd.read_csv(H1_DIR / "results/v3_pgls_lambda_profile.tsv", sep="\t")
    h1_sm = pd.read_csv(H1_DIR / "results/v3_pgls_statsmodels_verification.tsv", sep="\t")
    h1_clos = json.loads((H1_DIR / "results/v3_closure_verification.json").read_text())
    h1_comp = pd.read_csv(H1_DIR / "results/v3_comparator_metadata_summary.tsv", sep="\t")
    h1_coup = pd.read_csv(H1_DIR / "results/v3_coupling_and_comparator_audit.tsv", sep="\t")

    h2_v2_h1_doc = (H2_V2_DIR / "H1_COMPLETENESS.md").read_text()
    for _, row in h1_mod.iterrows():
        line_str = f"| {row['variable']} | {row['pgls_coef']:.6f} | {row['pgls_se_unb']:.6f} | {row['pgls_pval_unb']:.6e} | {row['ols_coef']:.6f} | {row['ols_se_unb']:.6f} | {row['ols_pval_unb']:.6e} |"
        assert line_str in h2_v2_h1_doc, f"Missing or mismatched row in h2_v2/H1_COMPLETENESS.md: {line_str}"

    for missing_id in h1_clos["missing_checkm2_faa_genomes"]:
        assert missing_id in h2_v2_h1_doc

    report["h1_verification"] = {
        "h2_v2_h1_completeness_repaired": True,
        "n_primary": int(h1_clos["n_primary"]),
        "n_s7_caller_complete_proxy": int(h1_clos["n_caller_complete_sensitivity"]),
        "missing_checkm2_faa_genomes": h1_clos["missing_checkm2_faa_genomes"],
        "primary_lambda_ml": float(h1_clos["primary_lambda_ml"]),
        "primary_lambda_ci95": h1_clos["primary_lambda_ci95"],
        "primary_r2_gls": float(h1_clos["primary_r2_gls"]),
        "ols_r2": float(h1_clos["ols_r2"]),
        "primary_sigma2_unb": float(h1_clos["primary_sigma2_unb"]),
        "ols_sigma2_unb": float(h1_prof.loc[h1_prof["lambda"] == 0.0, "sigma2_unb"].iloc[0]),
        "max_abs_diff_vs_statsmodels_From_table": {
            "beta": float(h1_clos["max_abs_diff_vs_statsmodels_beta"]),
            "se": float(h1_clos["max_abs_diff_vs_statsmodels_se"]),
            "r2": float(h1_clos["max_abs_diff_vs_statsmodels_r2"]),
            "verified_rows_in_v3_pgls_statsmodels_verification_tsv": len(h1_sm),
        },
        "models_S1_to_S7": h1_sens[
            ["model_id", "n", "p", "df_resid", "lambda_ml", "r2_gls", "coef_aai", "se_unb_aai", "p_unb_aai", "coef_frac_rbh", "se_unb_frac_rbh", "p_unb_frac_rbh"]
        ].to_dict(orient="records"),
        "comparator_summary_all_237": h1_comp.iloc[0].to_dict(),
    }

    # 2. Verify and recompute H2 statistics from local TSV tables
    h2_fam = pd.read_csv(H2_V2_DIR / "results/pilot_family_conservation.tsv", sep="\t")
    h2_nb = pd.read_csv(H2_V2_DIR / "results/pilot_neighbourhoods.tsv", sep="\t")
    h2_sum = json.loads((H2_V2_DIR / "results/pilot_conservation_summary.json").read_text())
    h2_join = json.loads((H2_V2_DIR / "results/pilot_join_metrics.json").read_text())

    # Attrition & Fisher exact test for differential Tier 1 survival
    k_fam = h2_fam[h2_fam["arm"] == "K"]
    q_fam = h2_fam[h2_fam["arm"] == "QnotK"]
    k_t1_n, k_tot = int(k_fam["eligible_primary"].sum()), len(k_fam)
    q_t1_n, q_tot = int(q_fam["eligible_primary"].sum()), len(q_fam)
    _, p_fisher_t1_survival = stats.fisher_exact([[k_t1_n, k_tot - k_t1_n], [q_t1_n, q_tot - q_t1_n]])

    # Recompute Mantel-Haenszel point estimates for Tier 1 and Tier 2
    def recompute_mh(df_eval, c_col, ec_col, er_col, sp_col, ko_col):
        med_ko = float(np.median(df_eval[ko_col]))
        strata = defaultdict(list)
        for _, r in df_eval.iterrows():
            s_key = (
                "sp2" if int(r[sp_col]) == 2 else "sp3plus",
                r["phylum_group"],
                "high_ko_opp" if float(r[ko_col]) > med_ko else "low_ko_opp",
            )
            strata[s_key].append(r)
        mh_ec, mh_c, mh_er, mh_den = 0.0, 0.0, 0.0, 0.0
        for s_key, items in strata.items():
            k_sub = [x for x in items if x["arm"] == "K"]
            q_sub = [x for x in items if x["arm"] == "QnotK"]
            nk, nq = len(k_sub), len(q_sub)
            if nk >= 1 and nq >= 1:
                w = (nk * nq) / (nk + nq)
                mh_den += w
                mh_ec += w * (np.mean([x[ec_col] for x in k_sub]) - np.mean([x[ec_col] for x in q_sub]))
                mh_c += w * (np.mean([x[c_col] for x in k_sub]) - np.mean([x[c_col] for x in q_sub]))
                mh_er += w * (np.mean([x[er_col] for x in k_sub]) - np.mean([x[er_col] for x in q_sub]))
        return {
            "n_strata": len(strata),
            "mh_weighted_excess_c_diff": round(float(mh_ec / mh_den), 6),
            "mh_weighted_raw_c_diff": round(float(mh_c / mh_den), 6),
            "mh_weighted_excess_r_diff": round(float(mh_er / mh_den), 6),
        }

    t1_eval = h2_fam[h2_fam["eligible_primary"] == 1].copy()
    t2_eval = h2_fam[h2_fam["eligible_stop3_sens"] == 1].copy()
    mh_t1 = recompute_mh(t1_eval, "c_fam_primary", "excess_c_fam_primary", "excess_r_fam_primary", "n_species_complete_window", "ko_annotation_opportunity")
    mh_t2 = recompute_mh(t2_eval, "c_fam_stop3_sens", "excess_c_fam_stop3", "excess_r_fam_stop3", "n_species_stop3_window", "ko_annotation_opportunity_stop3")

    assert mh_t1["mh_weighted_excess_c_diff"] == h2_sum["part_b_between_arm_covariate_stratified_permutation"]["tier1_primary"]["mh_weighted_excess_c_diff"]
    assert mh_t1["mh_weighted_raw_c_diff"] == h2_sum["part_b_between_arm_covariate_stratified_permutation"]["tier1_primary"]["mh_weighted_raw_c_diff"]
    assert mh_t2["mh_weighted_excess_c_diff"] == h2_sum["part_b_between_arm_covariate_stratified_permutation"]["tier2_stop3_sensitivity"]["mh_weighted_excess_c_diff"]
    assert mh_t2["mh_weighted_raw_c_diff"] == h2_sum["part_b_between_arm_covariate_stratified_permutation"]["tier2_stop3_sensitivity"]["mh_weighted_raw_c_diff"]

    # Recompute OLS/HC3 and Logit on t1_eval (n=353)
    t1_eval["is_k"] = (t1_eval["arm"] == "K").astype(float)
    t1_eval["length_100aa"] = t1_eval["length"].astype(float) / 100.0
    t1_eval["mean_plddt_scaled"] = (t1_eval["mean_plddt"].astype(float) - 0.70) * 10.0
    for pg in ["Actinomycetota", "multi", "other_bacteria_archaea"]:
        t1_eval[f"phylum_group_{pg}"] = (t1_eval["phylum_group"] == pg).astype(float)
    x_cols = [
        "is_k",
        "n_species_complete_window",
        "ko_annotation_opportunity",
        "length_100aa",
        "mean_plddt_scaled",
        "phylum_group_Actinomycetota",
        "phylum_group_multi",
        "phylum_group_other_bacteria_archaea",
    ]
    X_mat = sm.add_constant(t1_eval[x_cols].astype(float))
    ols_ec = sm.OLS(t1_eval["excess_c_fam_primary"].astype(float), X_mat).fit(cov_type="HC3")
    ols_c = sm.OLS(t1_eval["c_fam_primary"].astype(float), X_mat).fit(cov_type="HC3")
    logit_c = sm.Logit(t1_eval["c_fam_primary"].astype(float), X_mat).fit(disp=False, method="bfgs", maxiter=500)

    assert round(float(ols_ec.params["is_k"]), 6) == h2_sum["part_b_multivariable_ols_hc3_excess_c_fam"]["parameters"]["is_k"]["coef"]
    assert round(float(ols_c.params["is_k"]), 6) == h2_sum["part_b_multivariable_ols_hc3_raw_c_fam"]["parameters"]["is_k"]["coef"]
    assert round(float(logit_c.params["is_k"]), 6) == h2_sum["part_b_multivariable_logistic_regression_raw_c_fam"]["parameters"]["is_k"]["coef"]

    # Recompute cross-family dependence counts on Tier 1 evaluable families (n=353, 877 loci)
    t1_fams_set = set(t1_eval["family"])
    t1_loci_df = h2_nb[(h2_nb["family"].isin(t1_fams_set)) & (h2_nb["is_primary_locus"] == 1) & (h2_nb["eligible_locus_primary"] == 1)]
    sp_to_fams = defaultdict(set)
    bin_to_fams = defaultdict(set)
    contig_to_fams = defaultdict(set)
    for _, r in t1_loci_df.iterrows():
        sp_to_fams[r["species"]].add(r["family"])
        bin_to_fams[r["bin"]].add(r["family"])
        contig_to_fams[(r["bin"], r["contig"])].add(r["family"])
    shared_sp = {sp for sp, fs in sp_to_fams.items() if len(fs) >= 2}
    fam_sp_map = defaultdict(set)
    for _, r in t1_loci_df.iterrows():
        fam_sp_map[r["family"]].add(r["species"])
    disjoint_fams = t1_eval[t1_eval["family"].map(lambda fid: all(s not in shared_sp for s in fam_sp_map[fid]))]
    disj_k = disjoint_fams[disjoint_fams["arm"] == "K"]
    disj_q = disjoint_fams[disjoint_fams["arm"] == "QnotK"]

    dep_recomp = {
        "tier1_evaluable_families": len(t1_eval),
        "tier1_evaluable_primary_loci": len(t1_loci_df),
        "unique_bin_contig_pairs": len(contig_to_fams),
        "contigs_shared_across_multiple_families": sum(1 for fs in contig_to_fams.values() if len(fs) >= 2),
        "unique_refined_bins": len(bin_to_fams),
        "bins_shared_across_multiple_families": sum(1 for fs in bin_to_fams.values() if len(fs) >= 2),
        "unique_drep_species_clusters": len(sp_to_fams),
        "species_shared_across_multiple_families": len(shared_sp),
        "species_disjoint_subset": {
            "n_families_with_zero_shared_species": len(disjoint_fams),
            "n_K": len(disj_k),
            "n_QnotK": len(disj_q),
            "mean_excess_c_K": round(float(disj_k["excess_c_fam_primary"].mean()), 6),
            "mean_excess_c_QnotK": round(float(disj_q["excess_c_fam_primary"].mean()), 6),
            "diff_excess_c": round(float(disj_k["excess_c_fam_primary"].mean() - disj_q["excess_c_fam_primary"].mean()), 6),
        },
    }
    assert dep_recomp["unique_bin_contig_pairs"] == 869
    assert dep_recomp["contigs_shared_across_multiple_families"] == 8
    assert dep_recomp["species_disjoint_subset"]["n_families_with_zero_shared_species"] == 112

    report["h2_recomputed_and_verified"] = {
        "tier1_survival_by_arm": {
            "K": {"evaluable": k_t1_n, "total": k_tot, "rate": round(k_t1_n / k_tot, 6)},
            "QnotK": {"evaluable": q_t1_n, "total": q_tot, "rate": round(q_t1_n / q_tot, 6)},
            "p_fisher_two_sided": float(p_fisher_t1_survival),
        },
        "recomputed_mh_tier1": mh_t1,
        "recomputed_mh_tier2": mh_t2,
        "recomputed_ols_hc3_excess_is_k": {
            "coef": round(float(ols_ec.params["is_k"]), 6),
            "se_hc3": round(float(ols_ec.bse["is_k"]), 6),
            "p_value": round(float(ols_ec.pvalues["is_k"]), 6),
            "phylum_group_multi_coef": round(float(ols_ec.params["phylum_group_multi"]), 6),
            "phylum_group_multi_se": round(float(ols_ec.bse["phylum_group_multi"]), 6),
            "phylum_group_multi_p": round(float(ols_ec.pvalues["phylum_group_multi"]), 6),
        },
        "recomputed_ols_hc3_raw_is_k": {
            "coef": round(float(ols_c.params["is_k"]), 6),
            "se_hc3": round(float(ols_c.bse["is_k"]), 6),
            "p_value": round(float(ols_c.pvalues["is_k"]), 6),
            "phylum_group_multi_coef": round(float(ols_c.params["phylum_group_multi"]), 6),
            "phylum_group_multi_se": round(float(ols_c.bse["phylum_group_multi"]), 6),
            "phylum_group_multi_p": round(float(ols_c.pvalues["phylum_group_multi"]), 6),
        },
        "recomputed_logit_raw_is_k": {
            "coef": round(float(logit_c.params["is_k"]), 6),
            "se": round(float(logit_c.bse["is_k"]), 6),
            "p_value": round(float(logit_c.pvalues["is_k"]), 6),
            "odds_ratio": round(float(np.exp(logit_c.params["is_k"])), 6),
        },
        "recomputed_dependence_and_disjoint_subset": dep_recomp,
        "bin_verification_counts": h2_join.get("bin_verification_counts"),
        "n_bins_missing_annotations": len(h2_join.get("bins_missing_annotations", [])),
    }

    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n")
    print(f"Saved verified audit output to {OUT_JSON}")


if __name__ == "__main__":
    main()
